// Group equipment by primary category
export const equipmentByCategory = equipmentData.reduce(
  (acc, item) => {
    if (!acc[item.primaryCategory]) {
      acc[item.primaryCategory] = []
    }
    acc[item.primaryCategory].push(item)
    return acc
  },
  {} as Record<string, EquipmentItem[]>
)

// Get all unique categories
export const allCategories = Array.from(
  new Set(equipmentData.flatMap(item => item.categories))
).sort()
